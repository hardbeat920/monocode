// The phone's terminal is xterm.js in a WebView. This inlines xterm, its fit
// addon and the page's own script into one HTML string the app loads offline,
// so the screen needs no network and no file access.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const requireRoot = createRequire(resolve(mobile, "../package.json"));
const read = (path) => readFileSync(path, "utf8");
const xterm = dirname(requireRoot.resolve("@xterm/xterm/package.json"));
const fit = dirname(requireRoot.resolve("@xterm/addon-fit/package.json"));

// Script text sits inside a <script> element: nothing in it may close it early.
const inline = (code) => code.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:">
<style>${read(resolve(xterm, "css/xterm.css"))}</style>
<style>
html, body { margin: 0; height: 100%; overflow: hidden; -webkit-user-select: none; -webkit-touch-callout: none; -webkit-tap-highlight-color: transparent; }
#terminal { position: fixed; inset: 0; }
#overhang { position: fixed; pointer-events: none; white-space: pre; overflow: hidden; }
.xterm { padding: 6px 8px; height: 100%; box-sizing: border-box; }
/* xterm paints its scroll area black; the page's own colour shows instead. */
.xterm .xterm-viewport, .xterm .xterm-scrollable-element { background-color: transparent !important; }
/* History scrolls in #scroller, which shows iOS's own indicator instead. */
.xterm .xterm-scrollable-element > .scrollbar { display: none !important; }
#scroller { position: fixed; inset: 0; z-index: 10; overflow-x: hidden; overflow-y: scroll; -webkit-overflow-scrolling: touch; overscroll-behavior: contain; }
</style>
</head>
<body>
<div id="terminal"></div>
<div id="overhang"></div>
<div id="scroller"><div id="tall"></div></div>
<script>${inline(read(resolve(xterm, "lib/xterm.js")))}</script>
<script>${inline(read(resolve(fit, "lib/addon-fit.js")))}</script>
<script>${inline(read(resolve(mobile, "scripts/terminal-page/bootstrap.js")))}</script>
</body>
</html>
`;

const out = resolve(mobile, "src/features/terminal/terminalPage.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/generate-terminal-page.mjs. Do not edit.\nexport const TERMINAL_PAGE = ${JSON.stringify(html)};\n`,
);
console.log(`terminal page: ${(html.length / 1024).toFixed(0)} KB`);
